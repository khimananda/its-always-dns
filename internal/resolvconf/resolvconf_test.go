package resolvconf

import (
	"reflect"
	"strings"
	"testing"
)

func TestParseKubernetesPod(t *testing.T) {
	c := Parse(strings.NewReader(`# generated by kubelet
nameserver 10.96.0.10
search default.svc.cluster.local svc.cluster.local cluster.local ec2.internal
options ndots:5 timeout:2 ; trailing comment
`))
	want := Config{
		Nameservers: []string{"10.96.0.10"},
		Search:      []string{"default.svc.cluster.local", "svc.cluster.local", "cluster.local", "ec2.internal"},
		Ndots:       5,
		Options:     []string{"timeout:2"},
	}
	if !reflect.DeepEqual(c, want) {
		t.Errorf("got %+v", c)
	}
	if n := c.ExtraLookups("api.example.com"); n != 4 {
		t.Errorf("api.example.com should try 4 search domains first, got %d", n)
	}
	if n := c.ExtraLookups("api.example.com."); n != 0 {
		t.Errorf("a trailing dot skips the search list, got %d", n)
	}
	if n := c.ExtraLookups("a.b.c.d.e.f"); n != 0 {
		t.Errorf("five dots meets ndots:5, got %d", n)
	}
}

func TestParseDefaults(t *testing.T) {
	c := Parse(strings.NewReader("domain corp.example\nsearch a.example b.example\noptions ndots:99\n"))
	if c.Ndots != 15 {
		t.Errorf("ndots is capped at 15 like glibc, got %d", c.Ndots)
	}
	if !reflect.DeepEqual(c.Search, []string{"a.example", "b.example"}) {
		t.Errorf("last search line wins, got %v", c.Search)
	}
	if Parse(strings.NewReader("")).Ndots != 1 {
		t.Error("default ndots is 1")
	}
}
